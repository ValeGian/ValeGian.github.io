/**
 * Generates the Japanese → English name table used to show English titles for cards that
 * only exist in Japanese.
 *
 * TCGdex returns Japanese card names. A card name is a species name plus, usually, a
 * suffix: リザードンex is Charizard ex. Species names come from PokéAPI in one GraphQL
 * query; the suffixes are a short hand-written table, because they are a closed set that
 * changes once a generation.
 *
 *   node scripts/build-name-map.mjs
 */
import { writeFile } from 'node:fs/promises';

const ENDPOINT = 'https://graphql.pokeapi.co/v1beta2';
// Fetched by the browser at runtime, so it belongs in the served directory and
// nowhere else. One copy, one source of truth.
const OUT = 'public/data/card-names.json';

const QUERY = `{
  pokemonspeciesname(where: {language: {name: {_in: ["en", "ja-hrkt"]}}}) {
    name
    pokemon_species_id
    language { name }
  }
}`;

/** Trainer-owned cards prefix the owner: Nのレシラム is N's Reshiram. */
const OWNER_PREFIXES = new Map([
  ['Nの', "N's "],
  ['ハルトの', "Hop's "],
  ['ロケット団の', "Team Rocket's "],
  ['オーリムの', "Professor Sada's "],
  ['フトゥーの', "Professor Turo's "],
]);

const response = await fetch(ENDPOINT, {
  method: 'POST',
  headers: { 'Content-Type': 'application/json' },
  body: JSON.stringify({ query: QUERY }),
});

if (!response.ok) throw new Error(`PokéAPI responded ${response.status}`);
const { data, errors } = await response.json();
if (errors) throw new Error(`PokéAPI: ${JSON.stringify(errors)}`);

const english = new Map();
const japanese = new Map();
for (const row of data.pokemonspeciesname) {
  const target = row.language.name === 'en' ? english : japanese;
  target.set(row.pokemon_species_id, row.name);
}

const species = {};
for (const [id, kana] of japanese) {
  const name = english.get(id);
  if (name) species[kana] = name;
}

await writeFile(
  OUT,
  `${JSON.stringify(
    {
      note: 'Generated by scripts/build-name-map.mjs. Species names from PokéAPI; suffixes and owner prefixes maintained by hand.',
      generatedAt: new Date().toISOString(),
      species,
      ownerPrefixes: Object.fromEntries(OWNER_PREFIXES),
    },
    null,
    2,
  )}\n`,
);

console.log(`species mapped  ${Object.keys(species).length}`);
console.log(`written to      ${OUT}`);
